-- Migrasi: konfigurasi payment gateway (DOKU -> Xendit) + kanal QRIS
-- Tanggal: 2026-11-09
--
-- 1. Tabel t_payment_gateway: config non-rahasia per provider, dikelola admin
--    lewat dashboard. Secret (secret key / api key / callback token) TETAP di
--    .env — tidak pernah plaintext di DB.
-- 2. t_carabayar: kanal pembayaran aktif kini hanya QRIS (Xendit). VA bank
--    (id 3-9) dinonaktifkan menunggu aktivasi bank di akun Xendit.

CREATE TABLE IF NOT EXISTS t_payment_gateway (
    id_payment_gateway integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_provider varchar(30) NOT NULL,
    nama_provider varchar(100) NOT NULL,
    client_id varchar(120),
    is_prod boolean NOT NULL DEFAULT false,
    aktif boolean NOT NULL DEFAULT false,
    url_api varchar(255),
    url_callback varchar(255),
    endpoint_va varchar(120),
    endpoint_qris varchar(120),
    expired_menit smallint DEFAULT 20,
    metadata jsonb,
    keterangan text,
    created_at timestamp DEFAULT now(),
    updated_at timestamp DEFAULT now(),
    updated_by integer,
    CONSTRAINT t_payment_gateway_kode_unique UNIQUE (kode_provider)
);

