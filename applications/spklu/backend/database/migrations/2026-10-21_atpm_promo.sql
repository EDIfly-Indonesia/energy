-- =============================================================================
-- 8. fn_biaya_transaksi — SATU sumber angka untuk layar dan tagihan
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_biaya_transaksi(
  p_id_user      integer,
  p_chargebox_id varchar,
  p_connector_id integer,
  p_kwh          double precision,
  p_tanggal      date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  harga_normal    double precision,
  potongan_perkwh double precision,
  harga_efektif   double precision,
  kwh             double precision,
  biaya_energi    double precision,
  pju_persen      double precision,
  pju             double precision,
  pbjt_persen     double precision,
  pbjt            double precision,
  biaya_admin     double precision,
  kelas_layanan   varchar,
  biaya_layanan   double precision,
  ppn_persen      double precision,
  ppn             double precision,
  total           double precision,
  id_program      integer,
  nama_program    varchar,
  id_atpm_member  integer,
  berlaku_sampai  date,
  sisa_kuota      double precision
)
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
  v_harga_normal  double precision;
  v_ctype         varchar(20);
  v_id_mitra      integer;
  v_pju_pct       double precision := 0;
  v_is_pbjt       smallint := 0;
  v_pbjt_pct      double precision := 0;
  v_ppn_pct       double precision := 0;
  v_ppn_dasar     text := 'biaya_tambahan';
  v_potongan      double precision := 0;
  v_id_program    integer;
  v_nama_program  varchar(150);
  v_id_member     integer;
  v_selesai       date;
  v_kuota         double precision;
  v_terpakai      double precision;
  v_kwh           double precision;
  v_kelas         varchar(20);
  v_tarif_layanan double precision := 0;
  v_biaya_admin   double precision := 0;
  v_energi        double precision;
  v_pju           double precision;
  v_pbjt          double precision;
  v_ppn           double precision;
  v_dasar_ppn     double precision;
BEGIN
  v_kwh := GREATEST(COALESCE(p_kwh, 0), 0);

  SELECT d.harga_perkwh, d.connector_type, c.id_mitra,
         COALESCE(c.pju, 0), COALESCE(c.is_pbjt, 0), d.kelas_layanan
    INTO v_harga_normal, v_ctype, v_id_mitra,
         v_pju_pct, v_is_pbjt, v_kelas
    FROM t_connector_detail d
    JOIN t_chargebox c ON c.chargebox_id = d.chargebox_id
   WHERE d.chargebox_id = p_chargebox_id
     AND d.connector_id = p_connector_id;

  IF v_harga_normal IS NULL THEN
    RETURN;
  END IF;

  -- Pajak dibaca dari t_setting (sumber yang dipakai kode berjalan:
  -- global.gppn / global.gpbjt). Default 11% PPN, 3% PBJT.
  SELECT COALESCE(MAX(CASE WHEN nama_setting = 'ppn'  THEN NULLIF(value_setting,'')::double precision END), 11),
         COALESCE(MAX(CASE WHEN nama_setting = 'pbjt' THEN NULLIF(value_setting,'')::double precision END), 0),
         COALESCE(MAX(CASE WHEN nama_setting = 'ppn_dasar' THEN value_setting END), 'biaya_tambahan')
    INTO v_ppn_pct, v_pbjt_pct, v_ppn_dasar
    FROM t_setting
   WHERE nama_setting IN ('ppn','pbjt','ppn_dasar');

  SELECT COALESCE(t.biaya_per_sesi, 0) INTO v_tarif_layanan
    FROM t_tarif_layanan t
   WHERE t.kelas_layanan = v_kelas AND t.aktif
   LIMIT 1;
  v_tarif_layanan := COALESCE(v_tarif_layanan, 0);

  SELECT COALESCE(b.nilai, 0) INTO v_biaya_admin
    FROM t_biaya_platform b
   WHERE b.aktif AND (b.id_mitra = v_id_mitra OR b.id_mitra IS NULL)
   ORDER BY (b.id_mitra IS NULL) ASC, b.id DESC
   LIMIT 1;
  v_biaya_admin := COALESCE(v_biaya_admin, 0);

  SELECT m.id_atpm_member, pr.id_program, pr.nama, pr.tanggal_selesai,
         pr.kuota_kwh, pr.kuota_kwh_terpakai,
         COALESCE(pp.potongan_perkwh, pr.potongan_perkwh)
    INTO v_id_member, v_id_program, v_nama_program, v_selesai,
         v_kuota, v_terpakai, v_potongan
    FROM t_atpm_member m
    JOIN t_atpm_program pr ON pr.id_program = m.id_program
    JOIN t_atpm a          ON a.id_atpm    = pr.id_atpm
    LEFT JOIN t_atpm_program_potongan pp
           ON pp.id_program = pr.id_program
          AND pp.connector_type = v_ctype
   WHERE m.id_user = p_id_user
     AND m.status  = 'active'
     AND p_tanggal BETWEEN m.tanggal_mulai AND m.tanggal_selesai
     AND pr.aktif AND a.aktif
     AND p_tanggal BETWEEN pr.tanggal_mulai AND pr.tanggal_selesai
     AND (pr.kuota_kwh IS NULL OR pr.kuota_kwh_terpakai < pr.kuota_kwh)
     AND (
       NOT EXISTS (SELECT 1 FROM t_atpm_program_scope s WHERE s.id_program = pr.id_program)
       OR EXISTS (
            SELECT 1 FROM t_atpm_program_scope s
             WHERE s.id_program = pr.id_program
               AND (s.id_mitra     IS NULL OR s.id_mitra     = v_id_mitra)
               AND (s.chargebox_id IS NULL OR s.chargebox_id = p_chargebox_id)
               AND (s.connector_id IS NULL OR s.connector_id = p_connector_id)
          )
     )
   ORDER BY pr.prioritas DESC, pr.tanggal_selesai ASC, pr.id_program ASC
   LIMIT 1;

  v_potongan := LEAST(GREATEST(COALESCE(v_potongan, 0), 0), v_harga_normal);

  v_energi := round(((v_harga_normal - v_potongan) * v_kwh)::numeric, 2)::double precision;
  v_pju    := round((v_energi * COALESCE(v_pju_pct, 0) / 100.0)::numeric, 2)::double precision;
  v_pbjt   := CASE WHEN COALESCE(v_is_pbjt, 0) = 1
                   THEN round((v_energi * COALESCE(v_pbjt_pct, 0) / 100.0)::numeric, 2)::double precision
                   ELSE 0 END;

  v_dasar_ppn := CASE v_ppn_dasar
    WHEN 'energi'  THEN v_energi
    WHEN 'semua'   THEN v_energi + v_pju + v_pbjt + v_biaya_admin + v_tarif_layanan
    ELSE                v_biaya_admin + v_tarif_layanan
  END;
  v_ppn := round((v_dasar_ppn * COALESCE(v_ppn_pct, 0) / 100.0)::numeric, 2)::double precision;

  RETURN QUERY SELECT
    v_harga_normal,
    v_potongan,
    round((v_harga_normal - v_potongan)::numeric, 2)::double precision,
    v_kwh,
    v_energi,
    COALESCE(v_pju_pct, 0),
    v_pju,
    COALESCE(v_pbjt_pct, 0),
    v_pbjt,
    v_biaya_admin,
    v_kelas,
    v_tarif_layanan,
    COALESCE(v_ppn_pct, 0),
    v_ppn,
    -- Total dibulatkan ke rupiah penuh: gateway pembayaran memakai nominal
    -- integer, dan pembulatan dilakukan di server agar tampilan = tagihan.
    round((v_energi + v_pju + v_pbjt + v_biaya_admin + v_tarif_layanan + v_ppn)::numeric, 0)::double precision,
    v_id_program,
    v_nama_program,
    v_id_member,
    v_selesai,
    CASE WHEN v_kuota IS NULL THEN NULL::double precision ELSE v_kuota - v_terpakai END;
END;
$fn$;

-- =============================================================================
-- 9. klaim / lepas kuota promo (atomik)
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_atpm_klaim_kuota(
  p_id_program integer,
  p_kwh        double precision
)
RETURNS boolean
LANGUAGE plpgsql AS $fn$
DECLARE
  v_ok boolean := false;
BEGIN
  UPDATE t_atpm_program
     SET kuota_kwh_terpakai = kuota_kwh_terpakai + GREATEST(p_kwh, 0),
         updated_at = now()
   WHERE id_program = p_id_program
     AND (kuota_kwh IS NULL OR kuota_kwh_terpakai + GREATEST(p_kwh, 0) <= kuota_kwh)
  RETURNING true INTO v_ok;

  RETURN COALESCE(v_ok, false);
END;
$fn$;

CREATE OR REPLACE FUNCTION fn_atpm_lepas_kuota(
  p_id_program integer,
  p_kwh        double precision
)
RETURNS void
LANGUAGE plpgsql AS $fn$
BEGIN
  UPDATE t_atpm_program
     SET kuota_kwh_terpakai = GREATEST(kuota_kwh_terpakai - GREATEST(p_kwh, 0), 0),
         updated_at = now()
   WHERE id_program = p_id_program;
END;
$fn$;

