-- =============================================================================
-- Skema Promo ATPM + Biaya Layanan
-- File: 2026-10-21_atpm_promo.sql
--
-- Model harga sesuai keputusan bisnis:
--
--   harga_efektif_per_kwh = harga_perkwh_connector - potongan_promo_per_kwh
--   biaya_energi          = harga_efektif_per_kwh * X kWh
--
--   total = biaya_energi
--         + pju    (persen dari biaya_energi, dari t_chargebox.pju)
--         + pbjt   (persen dari biaya_energi, bila t_chargebox.is_pbjt = 1)
--         + biaya_admin_platform (flat / persen, dari t_biaya_platform)
--         + biaya_layanan        (per sesi, menurut kelas konektor)
--         + ppn    (persen, dasar pajak dapat dikonfigurasi)
--
-- Promo = POTONGAN RUPIAH PER kWh, bukan harga pengganti. Harga normal tidak
-- pernah diubah; promo adalah lapisan yang dihitung server.
--
-- SATU fungsi (fn_biaya_transaksi) menjadi sumber tunggal untuk layar
-- (getharga) dan pencatatan (simpanorder), supaya angka yang dilihat pengguna
-- identik dengan yang ditagihkan.
--
-- BELUM DIJALANKAN. Uji di dalam BEGIN ... ROLLBACK.
-- =============================================================================

BEGIN;

-- ------------------------------------------------------------- 1. master ATPM
CREATE TABLE IF NOT EXISTS t_atpm (
  id_atpm    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode       varchar(20)  NOT NULL,
  nama       varchar(100) NOT NULL,
  aktif      boolean      NOT NULL DEFAULT true,
  created_at timestamp    NOT NULL DEFAULT now(),
  updated_at timestamp    NOT NULL DEFAULT now(),
  CONSTRAINT t_atpm_kode_unique UNIQUE (kode)
);

-- --------------------------------------------------------- 2. program promo
CREATE TABLE IF NOT EXISTS t_atpm_program (
  id_program         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_atpm            integer NOT NULL,
  nama               varchar(150) NOT NULL,
  potongan_perkwh    double precision NOT NULL CHECK (potongan_perkwh >= 0),
  tanggal_mulai      date NOT NULL,
  tanggal_selesai    date NOT NULL,
  kuota_kwh          double precision,
  kuota_kwh_terpakai double precision NOT NULL DEFAULT 0,
  max_kwh_transaksi  double precision,
  prioritas          integer NOT NULL DEFAULT 100,
  aktif              boolean NOT NULL DEFAULT true,
  created_at         timestamp NOT NULL DEFAULT now(),
  updated_at         timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_atpm_program_atpm_fk
    FOREIGN KEY (id_atpm) REFERENCES t_atpm(id_atpm) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT t_atpm_program_periode_ck CHECK (tanggal_selesai >= tanggal_mulai),
  CONSTRAINT t_atpm_program_kuota_ck
    CHECK (kuota_kwh IS NULL OR kuota_kwh_terpakai <= kuota_kwh)
);

CREATE INDEX IF NOT EXISTS idx_atpm_program_aktif
  ON t_atpm_program (id_atpm, tanggal_mulai, tanggal_selesai) WHERE aktif;

CREATE TABLE IF NOT EXISTS t_atpm_program_potongan (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_program      integer NOT NULL,
  connector_type  varchar(20) NOT NULL,
  potongan_perkwh double precision NOT NULL CHECK (potongan_perkwh >= 0),
  CONSTRAINT t_atpm_program_potongan_program_fk
    FOREIGN KEY (id_program) REFERENCES t_atpm_program(id_program) ON DELETE CASCADE,
  CONSTRAINT t_atpm_program_potongan_unique UNIQUE (id_program, connector_type)
);

CREATE TABLE IF NOT EXISTS t_atpm_program_scope (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_program   integer NOT NULL,
  id_mitra     integer,
  chargebox_id varchar(50),
  connector_id smallint,
  CONSTRAINT t_atpm_program_scope_program_fk
    FOREIGN KEY (id_program) REFERENCES t_atpm_program(id_program) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_atpm_scope_program ON t_atpm_program_scope (id_program);

-- ------------------------------------------------------- 3. hak pelanggan
CREATE TABLE IF NOT EXISTS t_atpm_member (
  id_atpm_member  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user         integer NOT NULL,
  id_program      integer NOT NULL,
  vin             varchar(30),
  nomor_kartu     varchar(50),
  status          text NOT NULL DEFAULT 'active',
  tanggal_mulai   date NOT NULL,
  tanggal_selesai date NOT NULL,
  verified_by     integer,
  verified_at     timestamp,
  catatan         text,
  created_at      timestamp NOT NULL DEFAULT now(),
  updated_at      timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_atpm_member_user_fk
    FOREIGN KEY (id_user) REFERENCES t_user_mobile(id_user) ON DELETE CASCADE,
  CONSTRAINT t_atpm_member_program_fk
    FOREIGN KEY (id_program) REFERENCES t_atpm_program(id_program) ON DELETE RESTRICT,
  CONSTRAINT t_atpm_member_status_ck
    CHECK (status IN ('pending','active','suspended','expired')),
  CONSTRAINT t_atpm_member_periode_ck CHECK (tanggal_selesai >= tanggal_mulai),
  CONSTRAINT t_atpm_member_unique UNIQUE (id_user, id_program)
);

CREATE INDEX IF NOT EXISTS idx_atpm_member_user_aktif
  ON t_atpm_member (id_user, id_program) WHERE status = 'active';

