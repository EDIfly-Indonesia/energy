  jenis      text NOT NULL DEFAULT 'pertransaksi',
  nilai      double precision NOT NULL DEFAULT 0 CHECK (nilai >= 0),
  aktif      boolean NOT NULL DEFAULT true,
  updated_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_biaya_platform_jenis_ck
    CHECK (jenis IN ('pertransaksi','persen_energi'))
);

CREATE INDEX IF NOT EXISTS idx_biaya_platform_mitra
  ON t_biaya_platform (id_mitra) WHERE aktif;

