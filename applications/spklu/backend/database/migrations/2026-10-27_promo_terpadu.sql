BEGIN;

-- ============================================================ 1. mitra promo
CREATE TABLE IF NOT EXISTS t_promo_mitra (
  id_mitra_promo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jenis_mitra    varchar(20)  NOT NULL,
  kode           varchar(20)  NOT NULL,
  nama           varchar(150) NOT NULL,
  alamat         text,
  latitude       varchar(30),
  longitude      varchar(30),
  kontak_nama    varchar(100),
  kontak_email   varchar(100),
  kontak_hp      varchar(30),
  catatan        text,
  aktif          boolean NOT NULL DEFAULT true,

  -- API key untuk endpoint ATPM (machine-to-machine, POST /atpm/kendaraan).
  -- KEPUTUSAN: satu key per mitra, bukan banyak. Disimpan sebagai HASH
  -- (sha256), plaintext hanya ditampilkan sekali saat dibuat.
  -- Kosong = mitra belum punya akses API.
  api_key_hash      varchar(255),
  api_key_last_used timestamp,

  created_at     timestamp NOT NULL DEFAULT now(),
  updated_at     timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_mitra_jenis_ck
    CHECK (jenis_mitra IN ('atpm', 'hotel', 'asuransi', 'lainnya')),
  CONSTRAINT t_promo_mitra_kode_unique UNIQUE (kode),
  -- Satu key hanya boleh dimiliki satu mitra.
  CONSTRAINT t_promo_mitra_api_key_unique UNIQUE (api_key_hash)
);

CREATE INDEX IF NOT EXISTS idx_promo_mitra_jenis
  ON t_promo_mitra (jenis_mitra) WHERE aktif;

COMMENT ON COLUMN t_promo_mitra.jenis_mitra IS
  'atpm | hotel | asuransi | lainnya — menentukan aturan validasi yang dipakai.';
COMMENT ON COLUMN t_promo_mitra.latitude IS
  'Dipakai untuk hotel/asuransi (data lokasi mitra), bukan untuk geofence promo.';

-- ====================================================== 2. akun portal mitra
-- Portal dipakai hotel/asuransi untuk mendaftarkan email/no_hp pelanggan yang
-- berhak memakai kode promo (skenario 2 langkah 1.2, skenario 3 langkah 1.2).
CREATE TABLE IF NOT EXISTS t_portal_user (
  id_portal_user   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_mitra_promo   integer NOT NULL,
  email            varchar(100) NOT NULL,
  password_hash    varchar(255) NOT NULL,
  nama             varchar(100),
  role             varchar(20) NOT NULL DEFAULT 'operator',
  aktif            boolean NOT NULL DEFAULT true,
  last_login       timestamp,
  created_at       timestamp NOT NULL DEFAULT now(),
  updated_at       timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_portal_user_mitra_fk
    FOREIGN KEY (id_mitra_promo) REFERENCES t_promo_mitra(id_mitra_promo)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT t_portal_user_role_ck
    CHECK (role IN ('operator', 'admin_mitra')),
  CONSTRAINT t_portal_user_email_unique UNIQUE (email)
);

CREATE INDEX IF NOT EXISTS idx_portal_user_mitra
  ON t_portal_user (id_mitra_promo) WHERE aktif;

-- ============================================================== 3. kampanye
CREATE TABLE IF NOT EXISTS t_promo (
  id_promo            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_promo          varchar(30)  NOT NULL,
  id_mitra_promo      integer      NOT NULL,
  nama                varchar(150) NOT NULL,
  deskripsi           text,

  -- Aturan potongan. Potongan selalu berupa LAPISAN di atas harga normal;
  -- harga di t_connector_detail tidak pernah diubah.
  tipe_potongan       varchar(20)  NOT NULL DEFAULT 'per_kwh',
  nilai_potongan      double precision NOT NULL DEFAULT 0,
  maks_potongan       double precision,          -- cap rupiah per transaksi
  min_kwh             double precision NOT NULL DEFAULT 0,
  maks_kwh            double precision,          -- kWh yang boleh dapat potongan

  -- Budget promosi (nilai barter dari mitra), dalam RUPIAH.
  budget_rupiah       double precision NOT NULL DEFAULT 0,
  budget_terpakai     double precision NOT NULL DEFAULT 0,

  -- Kuota kWh bersifat opsional sebagai pembatas tambahan.
  kuota_kwh           double precision,
  kuota_kwh_terpakai  double precision NOT NULL DEFAULT 0,

  tanggal_mulai       date NOT NULL,
  tanggal_selesai     date NOT NULL,
  maks_pemakaian_per_user integer,               -- NULL = tanpa batas
  prioritas           integer NOT NULL DEFAULT 100,
  butuh_peserta       boolean NOT NULL DEFAULT true,
  cek_kendaraan       boolean NOT NULL DEFAULT false,
  aktif               boolean NOT NULL DEFAULT true,

  -- Kebijakan sisa budget saat periode berakhir (keputusan #6).
  --   hangus   : sisa tidak dipakai lagi
  --   rollover : sisa dipindahkan ke promo berikutnya (id_promo_lanjutan)
  kebijakan_sisa      varchar(10) NOT NULL DEFAULT 'hangus',
  id_promo_lanjutan   integer,

  dibuat_oleh         varchar(100),
  created_at          timestamp NOT NULL DEFAULT now(),
  updated_at          timestamp NOT NULL DEFAULT now(),

  CONSTRAINT t_promo_mitra_fk
    FOREIGN KEY (id_mitra_promo) REFERENCES t_promo_mitra(id_mitra_promo)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT t_promo_kode_unique UNIQUE (kode_promo),
  CONSTRAINT t_promo_kode_upper_ck CHECK (kode_promo = upper(kode_promo)),
  CONSTRAINT t_promo_kode_format_ck CHECK (kode_promo ~ '^[A-Z0-9_-]{3,30}$'),
  CONSTRAINT t_promo_tipe_ck
    CHECK (tipe_potongan IN ('per_kwh', 'persen', 'nominal')),
  CONSTRAINT t_promo_nilai_ck CHECK (nilai_potongan >= 0),
  CONSTRAINT t_promo_budget_ck
    CHECK (budget_rupiah >= 0 AND budget_terpakai >= 0
           AND budget_terpakai <= budget_rupiah),
  CONSTRAINT t_promo_kuota_ck
    CHECK (kuota_kwh IS NULL OR (kuota_kwh_terpakai >= 0 AND kuota_kwh_terpakai <= kuota_kwh)),
  CONSTRAINT t_promo_periode_ck CHECK (tanggal_selesai >= tanggal_mulai),
  CONSTRAINT t_promo_maks_kwh_ck CHECK (maks_kwh IS NULL OR maks_kwh > 0),
  CONSTRAINT t_promo_min_kwh_ck CHECK (min_kwh >= 0),
  CONSTRAINT t_promo_maks_pakai_ck
    CHECK (maks_pemakaian_per_user IS NULL OR maks_pemakaian_per_user > 0),
  CONSTRAINT t_promo_sisa_ck
    CHECK (kebijakan_sisa IN ('hangus', 'rollover')),
  -- Relasi ke promo berikutnya. Tidak diwajibkan NOT NULL saat pembuatan
  -- karena promo lanjutan biasanya dibuat belakangan; kelengkapannya
  -- ditegakkan saat penutupan periode (fn_promo_tutup_periode).
  CONSTRAINT t_promo_lanjutan_fk
    FOREIGN KEY (id_promo_lanjutan) REFERENCES t_promo(id_promo)
    ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT t_promo_lanjutan_self_ck
    CHECK (id_promo_lanjutan IS NULL OR id_promo_lanjutan <> id_promo)
);

CREATE INDEX IF NOT EXISTS idx_promo_validasi
  ON t_promo (kode_promo, tanggal_mulai, tanggal_selesai) WHERE aktif;

CREATE INDEX IF NOT EXISTS idx_promo_mitra
  ON t_promo (id_mitra_promo, prioritas DESC) WHERE aktif;

COMMENT ON COLUMN t_promo.budget_rupiah IS
  'Nilai promosi yang ditanggung mitra (barter iklan). Bukan settlement tunai.';
COMMENT ON COLUMN t_promo.budget_terpakai IS
  'Akumulasi potongan rupiah yang sudah diberikan ke pengguna.';
COMMENT ON COLUMN t_promo.cek_kendaraan IS
  'true untuk ATPM: pengguna harus punya kendaraan bermerek mitra ini.';
COMMENT ON COLUMN t_promo.butuh_peserta IS
  'true bila pengguna harus terdaftar di t_promo_peserta (hotel/asuransi/ATPM).';

-- ========================================================= 4. materi iklan
-- "File gambar promo ditampilkan di aplikasi sesuai ketentuan, mis. jumlah
-- tampil per hari". Batas harian ditegakkan dari t_promo_iklan_tayang.
CREATE TABLE IF NOT EXISTS t_promo_iklan (
  id_iklan            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_promo            integer NOT NULL,
  foto                varchar(255) NOT NULL,
  judul               varchar(150),
  target_url          varchar(255),
  maks_tayang_per_hari integer,                  -- NULL = tanpa batas
  tanggal_mulai       date,
  tanggal_selesai     date,
  urutan              integer NOT NULL DEFAULT 0,
  aktif               boolean NOT NULL DEFAULT true,
  created_at          timestamp NOT NULL DEFAULT now(),
  updated_at          timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_iklan_promo_fk
    FOREIGN KEY (id_promo) REFERENCES t_promo(id_promo) ON DELETE CASCADE,
  CONSTRAINT t_promo_iklan_tayang_ck
    CHECK (maks_tayang_per_hari IS NULL OR maks_tayang_per_hari > 0),
  CONSTRAINT t_promo_iklan_periode_ck
    CHECK (tanggal_selesai IS NULL OR tanggal_mulai IS NULL
           OR tanggal_selesai >= tanggal_mulai)
);

CREATE INDEX IF NOT EXISTS idx_promo_iklan_promo
  ON t_promo_iklan (id_promo, urutan) WHERE aktif;

CREATE TABLE IF NOT EXISTS t_promo_iklan_tayang (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_iklan     integer NOT NULL,
  id_user      integer,
  tanggal      date NOT NULL DEFAULT CURRENT_DATE,
  created_at   timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_iklan_tayang_fk
    FOREIGN KEY (id_iklan) REFERENCES t_promo_iklan(id_iklan) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_promo_tayang_harian
  ON t_promo_iklan_tayang (id_iklan, tanggal);

COMMENT ON TABLE t_promo_iklan_tayang IS
  'Satu baris = satu impresi. Dipakai menghitung batas tampil per hari.';

-- ================================================== 5. kendaraan pengguna
-- t_user_mobile TIDAK menyimpan data kendaraan, padahal skenario ATPM
-- mewajibkan cek "ATPM sesuai dengan tipe kendaraan".
CREATE TABLE IF NOT EXISTS t_user_kendaraan (
  id_kendaraan    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user         integer NOT NULL,
  id_mitra_promo  integer,
  merek           varchar(60),
  tipe            varchar(60),
  tahun           integer,
  vin             varchar(30),
  nomor_polisi    varchar(20),
  aktif           boolean NOT NULL DEFAULT true,
  -- Asal data (keputusan #3): 'atpm_endpoint' = dikirim ATPM lewat API
  -- dengan body {email, kode_promo}; 'app' = diisi pengguna; 'admin' = manual.
  sumber          varchar(20) NOT NULL DEFAULT 'app',
  created_at      timestamp NOT NULL DEFAULT now(),
  updated_at      timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_user_kendaraan_user_fk
    FOREIGN KEY (id_user) REFERENCES t_user_mobile(id_user) ON DELETE CASCADE,
  CONSTRAINT t_user_kendaraan_mitra_fk
    FOREIGN KEY (id_mitra_promo) REFERENCES t_promo_mitra(id_mitra_promo)
    ON UPDATE RESTRICT ON DELETE SET NULL,
  CONSTRAINT t_user_kendaraan_tahun_ck
    CHECK (tahun IS NULL OR (tahun BETWEEN 1950 AND 2100)),
  CONSTRAINT t_user_kendaraan_sumber_ck
    CHECK (sumber IN ('app', 'atpm_endpoint', 'admin'))
);

-- Satu pengguna hanya boleh punya satu catatan kepemilikan per merek (mitra
-- promo). Endpoint ATPM mengirim {email, kode_promo} tanpa merek/tipe, jadi
-- yang disimpan adalah klaim "pengguna ini memiliki kendaraan merek X".
CREATE UNIQUE INDEX IF NOT EXISTS t_user_kendaraan_user_mitra_unique
  ON t_user_kendaraan (id_user, id_mitra_promo)
  WHERE id_mitra_promo IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS t_user_kendaraan_vin_unique
  ON t_user_kendaraan (id_user, upper(vin)) WHERE vin IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_user_kendaraan_mitra
  ON t_user_kendaraan (id_user, id_mitra_promo) WHERE aktif;

-- ==================================================== 6. peserta promo
-- Satu tabel untuk dua jalur:
--   a) hotel/asuransi mendaftarkan tamu/pelanggan (id_user NULL, email/no_hp diisi)
--   b) ATPM mendaftarkan pemilik kendaraan (id_user dan/atau vin diisi)
-- Validasi mencocokkan id_user, atau email/no_hp akun mobile.
CREATE TABLE IF NOT EXISTS t_promo_peserta (
  id_peserta       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_promo         integer NOT NULL,
  id_user          integer,
  email            varchar(100),
  no_hp            varchar(30),
  vin              varchar(30),
  status           varchar(20) NOT NULL DEFAULT 'active',
  tanggal_mulai    date,
  tanggal_selesai  date,
  id_portal_user   integer,
  catatan          text,
  created_at       timestamp NOT NULL DEFAULT now(),
  updated_at       timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_peserta_promo_fk
    FOREIGN KEY (id_promo) REFERENCES t_promo(id_promo) ON DELETE CASCADE,
  CONSTRAINT t_promo_peserta_user_fk
    FOREIGN KEY (id_user) REFERENCES t_user_mobile(id_user) ON DELETE CASCADE,
  CONSTRAINT t_promo_peserta_portal_fk
    FOREIGN KEY (id_portal_user) REFERENCES t_portal_user(id_portal_user)
    ON UPDATE RESTRICT ON DELETE SET NULL,
  CONSTRAINT t_promo_peserta_status_ck
    CHECK (status IN ('pending', 'active', 'suspended', 'expired')),
  CONSTRAINT t_promo_peserta_periode_ck
    CHECK (tanggal_selesai IS NULL OR tanggal_mulai IS NULL
           OR tanggal_selesai >= tanggal_mulai),
  CONSTRAINT t_promo_peserta_identitas_ck
    CHECK (id_user IS NOT NULL OR email IS NOT NULL OR no_hp IS NOT NULL OR vin IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS t_promo_peserta_email_unique
  ON t_promo_peserta (id_promo, lower(email)) WHERE email IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS t_promo_peserta_hp_unique
  ON t_promo_peserta (id_promo, no_hp) WHERE no_hp IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS t_promo_peserta_user_unique
  ON t_promo_peserta (id_promo, id_user) WHERE id_user IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_promo_peserta_aktif
  ON t_promo_peserta (id_promo, status) WHERE status = 'active';

-- ===================================================== 7. ledger pemakaian
CREATE TABLE IF NOT EXISTS t_promo_pemakaian (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_promo          integer NOT NULL,
  id_peserta        integer,
  id_user           integer NOT NULL,
  no_trans          varchar(50) NOT NULL,
  kwh               double precision NOT NULL DEFAULT 0,
  harga_normal      double precision NOT NULL DEFAULT 0,
  potongan_perkwh   double precision NOT NULL DEFAULT 0,
  harga_efektif     double precision NOT NULL DEFAULT 0,
  potongan_rupiah   double precision NOT NULL DEFAULT 0,   -- yang menggerus budget
  status            varchar(20) NOT NULL DEFAULT 'aktif',
  -- Diisi saat status = 'gagal_klaim': alasan dari fn_promo_validasi yang
  -- membuat klaim tidak bisa dilakukan (mis. BUDGET_HABIS).
  alasan            varchar(30),
  created_at        timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_pemakaian_promo_fk
    FOREIGN KEY (id_promo) REFERENCES t_promo(id_promo) ON DELETE RESTRICT,
  CONSTRAINT t_promo_pemakaian_peserta_fk
    FOREIGN KEY (id_peserta) REFERENCES t_promo_peserta(id_peserta) ON DELETE SET NULL,
  -- 'gagal_klaim' = pembayaran sudah diterima tetapi budget tidak cukup saat
  -- klaim. Budget TIDAK berkurang; baris ini hanya jejak eksposur untuk
  -- laporan (lihat v_promo_eksposur). Lihat TODO-PROMO.md §0.A.
  CONSTRAINT t_promo_pemakaian_status_ck
    CHECK (status IN ('aktif', 'dibatalkan', 'gagal_klaim')),
  CONSTRAINT t_promo_pemakaian_notrans_unique UNIQUE (no_trans)
);

CREATE INDEX IF NOT EXISTS idx_promo_pemakaian_gagal
  ON t_promo_pemakaian (id_promo, created_at) WHERE status = 'gagal_klaim';

CREATE INDEX IF NOT EXISTS idx_promo_pemakaian_user
  ON t_promo_pemakaian (id_promo, id_user) WHERE status = 'aktif';

COMMENT ON COLUMN t_promo_pemakaian.potongan_rupiah IS
  'Nilai potongan yang dibebankan ke budget mitra. Sumber perhitungan sisa budget.';

-- ================================================== 7b. rollover sisa budget
-- Jejak pemindahan sisa budget dari satu periode promo ke periode berikutnya
-- (keputusan #6). Satu promo sumber hanya boleh ditutup sekali.
CREATE TABLE IF NOT EXISTS t_promo_rollover (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_promo_asal     integer NOT NULL,
  id_promo_tujuan   integer NOT NULL,
  jumlah            double precision NOT NULL CHECK (jumlah > 0),
  tanggal_tutup     date NOT NULL DEFAULT CURRENT_DATE,
  created_at        timestamp NOT NULL DEFAULT now(),
  CONSTRAINT t_promo_rollover_asal_fk
    FOREIGN KEY (id_promo_asal) REFERENCES t_promo(id_promo) ON DELETE RESTRICT,
  CONSTRAINT t_promo_rollover_tujuan_fk
    FOREIGN KEY (id_promo_tujuan) REFERENCES t_promo(id_promo) ON DELETE RESTRICT,
  CONSTRAINT t_promo_rollover_beda_ck CHECK (id_promo_asal <> id_promo_tujuan),
  CONSTRAINT t_promo_rollover_asal_unique UNIQUE (id_promo_asal)
);

COMMENT ON TABLE t_promo_rollover IS
  'Audit pemindahan sisa budget antar periode promo (kebijakan_sisa = rollover).';

