-- 11d. fn_promo_iklan_untuk_user — batas tayang PER PENGGUNA (keputusan #4)
--
-- View v_promo_iklan_tayang_hari_ini menghitung total tayang global (untuk
-- admin). Endpoint aplikasi memakai fungsi ini supaya tiap pengguna mendapat
-- jatah tayang sendiri: maks_tayang_per_hari dihitung per id_user.
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_promo_iklan_untuk_user(
  p_id_user integer,
  p_tanggal date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  id_iklan             integer,
  id_promo             integer,
  kode_promo           varchar,
  nama_promo           varchar,
  nama_mitra           varchar,
  foto                 varchar,
  judul                varchar,
  target_url           varchar,
  urutan               integer,
  maks_tayang_per_hari integer,
  tayang_hari_ini      integer,
  masih_bisa_tayang    boolean
)
LANGUAGE sql STABLE AS $fn$
  SELECT
    i.id_iklan,
    i.id_promo,
    p.kode_promo,
    p.nama,
    m.nama,
    i.foto,
    i.judul,
    i.target_url,
    i.urutan,
    i.maks_tayang_per_hari,
    COALESCE(t.jumlah, 0)::integer,
    (i.maks_tayang_per_hari IS NULL
     OR COALESCE(t.jumlah, 0) < i.maks_tayang_per_hari)
  FROM t_promo_iklan i
  JOIN t_promo p       ON p.id_promo = i.id_promo
  JOIN t_promo_mitra m ON m.id_mitra_promo = p.id_mitra_promo
  LEFT JOIN (
    SELECT it.id_iklan, count(*) AS jumlah
      FROM t_promo_iklan_tayang it
     WHERE it.tanggal = p_tanggal
       AND it.id_user = p_id_user
     GROUP BY it.id_iklan
  ) t ON t.id_iklan = i.id_iklan
  WHERE i.aktif
    AND p.aktif
    AND (i.tanggal_mulai   IS NULL OR p_tanggal >= i.tanggal_mulai)
    AND (i.tanggal_selesai IS NULL OR p_tanggal <= i.tanggal_selesai)
    AND p_tanggal BETWEEN p.tanggal_mulai AND p.tanggal_selesai
    AND (p.budget_rupiah - p.budget_terpakai) > 0
  ORDER BY i.urutan, i.id_iklan;
$fn$;

COMMENT ON FUNCTION fn_promo_iklan_untuk_user(integer, date) IS
  'Iklan layak tayang untuk satu pengguna; batas harian dihitung per pengguna.';

