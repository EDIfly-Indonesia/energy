-- =============================================================================
-- 11. fn_biaya_transaksi — satu sumber angka (KEPUTUSAN §2) + promo
--
-- PENTING: fungsi ini SUDAH ADA di DB live dengan signature 4 argumen dan
-- sudah dipakai controller-chargebox.js (getharga) dan controller-transaction.js
-- (simpanorder) lewat `fn_biaya_transaksi($1,$2,$3,0)`.
--
-- Karena itu signature baru dibuat KOMPATIBEL MUNDUR:
--   - 4 parameter pertama sama persis, urutan sama
--   - 3 parameter baru (p_id_user, p_tanggal, p_kode_promo) diberi DEFAULT
--   - 14 kolom hasil pertama sama persis, urutan dan nama sama
--   - kolom promo ditambahkan di BELAKANG (additive, sesuai KEPUTUSAN §8.2)
--
-- Fungsi lama 4-argumen di-DROP lebih dulu. Tanpa DROP, PostgreSQL menyimpan
-- keduanya sebagai overload dan pemanggilan 4 argumen akan memilih yang lama,
-- sehingga promo tidak pernah dihitung.
--
-- Rumus:
--   potongan_manual = p_potongan_perkwh (harga member/promo manual dari klien)
--   potongan_promo  = dari fn_promo_validasi (sudah dibatasi sisa budget)
--   total_potongan_rupiah = LEAST(manual*kwh + promo, harga*kwh)
--   biaya_energi    = round(harga*kwh - total_potongan_rupiah)
--   PBJT-TL         = t_area.pbjt% x biaya_energi
--   biaya_platform  = t_biaya 'admin_platform'
--   biaya_layanan   = t_biaya 'layanan_<kelas>'
--   DPP             = energi + platform + layanan      (TANPA pbjt)
--   PPN             = t_setting.ppn% x DPP
--   total           = energi + pbjt + platform + layanan + ppn
-- =============================================================================
DROP FUNCTION IF EXISTS fn_biaya_transaksi(varchar, integer, double precision, double precision);

CREATE OR REPLACE FUNCTION fn_biaya_transaksi(
  p_chargebox_id    varchar,
  p_connector_id    integer,
  p_kwh             double precision,
  p_potongan_perkwh double precision DEFAULT 0,
  p_id_user         integer DEFAULT NULL,
  p_tanggal         date DEFAULT CURRENT_DATE,
  p_kode_promo      varchar DEFAULT NULL
)
RETURNS TABLE (
  -- 14 kolom lama, nama dan urutan dipertahankan
  harga_normal     double precision,
  potongan_perkwh  double precision,
  harga_efektif    double precision,
  kwh              double precision,
  biaya_energi     double precision,
  pbjt_persen      double precision,
  pbjt             double precision,
  biaya_platform   double precision,
  biaya_layanan    double precision,
  kelas_layanan    varchar,
  dpp              double precision,
  ppn_persen       double precision,
  ppn              double precision,
  total            double precision,
  -- kolom promo (additive)
  id_promo         integer,
  kode_promo       varchar,
  nama_promo       varchar,
  potongan_rupiah  double precision,
  potongan_dibatasi boolean,
  id_peserta       integer,
  promo_alasan     text
)
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
  v_harga        double precision;
  v_kelas        varchar(20);
  v_id_area      integer;
  v_kwh          double precision;
  v_pbjt_pct     double precision := 0;
  v_ppn_pct      double precision := 0;
  v_platform     double precision := 0;
  v_layanan      double precision := 0;
  v_pot_manual   double precision := 0;
  v_pot_promo    double precision := 0;
  v_pot_total    double precision := 0;
  v_energi       double precision;
  v_pbjt         double precision;
  v_dpp          double precision;
  v_ppn          double precision;
  v_total        double precision;
  -- promo (nama variabel dibedakan dari nama kolom OUT agar tidak ambigu)
  v_p_valid      boolean := false;
  v_p_id         integer;
  v_p_kode       varchar(30);
  v_p_nama       varchar(150);
  v_p_peserta    integer;
  v_p_alasan     text;
  v_p_dibatasi   boolean := false;
BEGIN
  v_kwh := GREATEST(COALESCE(p_kwh, 0), 0);

  SELECT d.harga_perkwh, d.kelas_layanan, c.id_area
    INTO v_harga, v_kelas, v_id_area
    FROM t_connector_detail d
    JOIN t_chargebox c ON c.chargebox_id = d.chargebox_id
   WHERE d.chargebox_id = p_chargebox_id
     AND d.connector_id = p_connector_id;

  IF v_harga IS NULL THEN
    RETURN; -- konektor tidak ditemukan -> hasil kosong
  END IF;

  SELECT COALESCE(a.pbjt, 0) INTO v_pbjt_pct
    FROM t_area a WHERE a.id_area = v_id_area;
  v_pbjt_pct := COALESCE(v_pbjt_pct, 0);

  SELECT COALESCE(MAX(CASE WHEN nama_setting = 'ppn'
                           THEN NULLIF(value_setting, '')::double precision END), 11)
    INTO v_ppn_pct
    FROM t_setting WHERE nama_setting = 'ppn';
  v_ppn_pct := COALESCE(v_ppn_pct, 11);

  -- Biaya platform & layanan dari t_biaya (id_mitra 0 = global).
  SELECT COALESCE(b.default_biaya, 0) INTO v_platform
    FROM t_biaya b
   WHERE b.kode_biaya = 'admin_platform' AND b.id_mitra = 0
   LIMIT 1;

  SELECT COALESCE(b.default_biaya, 0) INTO v_layanan
    FROM t_biaya b
   WHERE b.kode_biaya = 'layanan_' || v_kelas AND b.id_mitra = 0
   LIMIT 1;

  -- Potongan manual (harga member / promo yang sudah dihitung klien).
  v_pot_manual := LEAST(GREATEST(COALESCE(p_potongan_perkwh, 0), 0), v_harga);

  -- Potongan promo dari kode promo (bila ada).
  IF p_kode_promo IS NOT NULL AND btrim(p_kode_promo) <> '' THEN
    SELECT pv.valid, pv.alasan, pv.id_promo, pv.kode_promo, pv.nama_promo,
           pv.id_peserta, pv.potongan_rupiah, pv.potongan_dibatasi
      INTO v_p_valid, v_p_alasan, v_p_id, v_p_kode, v_p_nama,
           v_p_peserta, v_pot_promo, v_p_dibatasi
      FROM fn_promo_validasi(p_id_user, p_kode_promo, p_chargebox_id,
                             p_connector_id, v_kwh, p_tanggal) pv;
    IF NOT COALESCE(v_p_valid, false) THEN
      v_pot_promo := 0;
      v_p_dibatasi := false;
    END IF;
  END IF;

  -- Total potongan dalam rupiah, tidak boleh melebihi biaya energi.
  v_pot_total := LEAST(
    (v_pot_manual * v_kwh) + COALESCE(v_pot_promo, 0),
    v_harga * v_kwh
  );
  v_pot_total := round(GREATEST(v_pot_total, 0)::numeric, 2)::double precision;

  -- Komponen rupiah dibulatkan SEBELUM dijumlah (layar = tagihan).
  v_energi := round((v_harga * v_kwh - v_pot_total)::numeric)::double precision;
  v_pbjt   := round((v_energi * v_pbjt_pct / 100.0)::numeric)::double precision;
  v_platform := round(COALESCE(v_platform, 0)::numeric)::double precision;
  v_layanan  := round(COALESCE(v_layanan, 0)::numeric)::double precision;

  -- DPP tanpa PBJT (PPN dan PBJT tidak saling mengkonsumsi basis).
  v_dpp := v_energi + v_platform + v_layanan;
  v_ppn := round((v_dpp * v_ppn_pct / 100.0)::numeric)::double precision;
  v_total := v_energi + v_pbjt + v_platform + v_layanan + v_ppn;

  RETURN QUERY SELECT
    v_harga,
    CASE WHEN v_kwh > 0
         THEN round((v_pot_total / v_kwh)::numeric, 2)::double precision
         ELSE 0::double precision END,
    round((v_harga - CASE WHEN v_kwh > 0
                          THEN v_pot_total / v_kwh
                          ELSE 0 END)::numeric, 2)::double precision,
    v_kwh,
    v_energi,
    v_pbjt_pct,
    v_pbjt,
    v_platform,
    v_layanan,
    v_kelas,
    v_dpp,
    v_ppn_pct,
    v_ppn,
    v_total,
    v_p_id,
    v_p_kode,
    v_p_nama,
    v_pot_promo,
    v_p_dibatasi,
    v_p_peserta,
    v_p_alasan;
END;
$fn$;

COMMENT ON FUNCTION fn_biaya_transaksi(varchar, integer, double precision, double precision, integer, date, varchar) IS
  'Sumber tunggal perhitungan biaya. 4 argumen pertama kompatibel dengan pemanggil lama. p_kode_promo opsional; bila tidak valid, alasan diisi dan potongan promo 0.';

-- =============================================================================
-- 11b. fn_kendaraan_daftar — endpoint ATPM (keputusan #3)
--
-- ATPM mengirim body {email, kode_promo}. Dari situ:
--   kode_promo -> t_promo -> id_mitra_promo (merek ATPM)
--   email      -> t_user_mobile.id_user
-- lalu dicatat:
--   1. klaim merek di t_user_kendaraan (sumber 'atpm_endpoint')
--   2. keanggotaan promo di t_promo_peserta
--
-- Keduanya diperlukan karena keputusan #2 mewajibkan DUA syarat sekaligus:
-- pengguna terdaftar sebagai peserta DAN memiliki kendaraan merek tersebut.
-- Endpoint ini melakukan keduanya sekaligus supaya ATPM cukup satu panggilan.
--
-- Merek diwakili id_mitra_promo, bukan kolom merek terpisah: jenis mitra
-- (atpm/hotel/asuransi) sudah ada di t_promo_mitra.
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_kendaraan_daftar(
  p_email      varchar,
  p_kode_promo varchar,
  p_sumber     varchar DEFAULT 'atpm_endpoint'
)
RETURNS TABLE (
  ok             boolean,
  status         text,
  id_user        integer,
  id_mitra_promo integer,
  id_peserta     integer
)
LANGUAGE plpgsql AS $fn$
DECLARE
  v_kode      varchar(30);
  v_promo     t_promo%ROWTYPE;
  v_jenis     varchar(20);
  v_user      integer;
  v_peserta   integer;
  v_ok        boolean := false;
  v_status    text;
BEGIN
  v_kode := upper(btrim(COALESCE(p_kode_promo, '')));

  IF COALESCE(btrim(p_email), '') = '' THEN
    v_status := 'EMAIL_KOSONG';
  ELSIF v_kode = '' THEN
    v_status := 'KODE_KOSONG';
  END IF;

  IF v_status IS NULL THEN
    SELECT t.* INTO v_promo FROM t_promo t WHERE t.kode_promo = v_kode;
    IF NOT FOUND THEN
      v_status := 'KODE_TIDAK_DITEMUKAN';
    ELSE
      SELECT m.jenis_mitra INTO v_jenis
        FROM t_promo_mitra m WHERE m.id_mitra_promo = v_promo.id_mitra_promo;
      IF v_jenis IS DISTINCT FROM 'atpm' THEN
        v_status := 'BUKAN_PROMO_ATPM';
      END IF;
    END IF;
  END IF;

  IF v_status IS NULL THEN
    SELECT u.id_user INTO v_user
      FROM t_user_mobile u
     WHERE lower(u.email) = lower(btrim(p_email))
       AND u.deleted_at IS NULL
     LIMIT 1;
    IF v_user IS NULL THEN
      v_status := 'USER_TIDAK_DITEMUKAN';
    END IF;
  END IF;

  IF v_status IS NULL THEN
    -- 1. Klaim merek. Idempoten: pemanggilan ulang tidak menggandakan baris
    --    (dijaga unique index t_user_kendaraan_user_mitra_unique).
    IF NOT EXISTS (
      SELECT 1 FROM t_user_kendaraan k
       WHERE k.id_user = v_user AND k.id_mitra_promo = v_promo.id_mitra_promo
    ) THEN
      INSERT INTO t_user_kendaraan (id_user, id_mitra_promo, aktif, sumber)
      VALUES (v_user, v_promo.id_mitra_promo, true, p_sumber);
    ELSE
      UPDATE t_user_kendaraan k
         SET aktif = true, sumber = p_sumber, updated_at = now()
       WHERE k.id_user = v_user AND k.id_mitra_promo = v_promo.id_mitra_promo;
    END IF;

    -- 2. Keanggotaan promo.
    SELECT ps.id_peserta INTO v_peserta
      FROM t_promo_peserta ps
     WHERE ps.id_promo = v_promo.id_promo
       AND ps.id_user = v_user
     LIMIT 1;

    IF v_peserta IS NULL THEN
      INSERT INTO t_promo_peserta (id_promo, id_user, status, tanggal_mulai, tanggal_selesai)
      VALUES (v_promo.id_promo, v_user, 'active',
              v_promo.tanggal_mulai, v_promo.tanggal_selesai)
      -- Kualifikasi: id_peserta juga nama kolom OUT, tanpa ini PostgreSQL
      -- menolak "column reference is ambiguous".
      RETURNING t_promo_peserta.id_peserta INTO v_peserta;
    END IF;

    v_ok := true;
    v_status := 'TERDAFTAR';
  END IF;

  RETURN QUERY SELECT v_ok, v_status, v_user, v_promo.id_mitra_promo, v_peserta;
END;
$fn$;

COMMENT ON FUNCTION fn_kendaraan_daftar(varchar, varchar, varchar) IS
  'Endpoint ATPM: body {email, kode_promo} -> catat merek kendaraan + keanggotaan promo.';

-- =============================================================================
-- 11c. fn_promo_tutup_periode — hangus atau rollover (keputusan #6)
--
-- Dipanggil job harian setelah tanggal_selesai terlewati, atau manual admin.
--   hangus   : sisa budget dibiarkan (tidak dipakai lagi), tidak ada perubahan
--   rollover : sisa dipindahkan ke t_promo.id_promo_lanjutan sebagai tambahan
--              budget_rupiah, dan budget_terpakai promo asal disetel penuh
--              supaya sisa terbaca 0 (tidak terhitung dua kali)
-- Setiap pemindahan dicatat di t_promo_rollover (audit + cegah dobel).
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_promo_tutup_periode(
  p_id_promo integer,
  p_tanggal  date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  status         text,
  id_promo_asal  integer,
  id_promo_tujuan integer,
  jumlah         double precision
)
LANGUAGE plpgsql AS $fn$
DECLARE
  v_promo   t_promo%ROWTYPE;
  v_sisa    double precision;
  v_tujuan  integer;
  v_next    integer;
  v_loop    integer := 0;
  v_status  text;
BEGIN
  SELECT t.* INTO v_promo FROM t_promo t WHERE t.id_promo = p_id_promo FOR UPDATE;

  IF NOT FOUND THEN
    RETURN QUERY SELECT 'PROMO_TIDAK_DITEMUKAN'::text, p_id_promo, NULL::integer, 0::double precision;
    RETURN;
  END IF;

  IF p_tanggal <= v_promo.tanggal_selesai THEN
    RETURN QUERY SELECT 'BELUM_BERAKHIR'::text, p_id_promo, NULL::integer, 0::double precision;
    RETURN;
  END IF;

  v_sisa := v_promo.budget_rupiah - v_promo.budget_terpakai;
  IF v_sisa <= 0 THEN
    RETURN QUERY SELECT 'TIDAK_ADA_SISA'::text, p_id_promo, NULL::integer, 0::double precision;
    RETURN;
  END IF;

  IF v_promo.kebijakan_sisa = 'hangus' THEN
    RETURN QUERY SELECT 'HANGUS'::text, p_id_promo, NULL::integer, v_sisa;
    RETURN;
  END IF;

  -- rollover
  IF v_promo.id_promo_lanjutan IS NULL THEN
    RETURN QUERY SELECT 'LANJUTAN_BELUM_DITETAPKAN'::text, p_id_promo, NULL::integer, v_sisa;
    RETURN;
  END IF;

  IF EXISTS (SELECT 1 FROM t_promo_rollover r WHERE r.id_promo_asal = p_id_promo) THEN
    RETURN QUERY SELECT 'SUDAH_DITUTUP'::text, p_id_promo, v_promo.id_promo_lanjutan, 0::double precision;
    RETURN;
  END IF;

  v_tujuan := v_promo.id_promo_lanjutan;

  -- Cegah rantai melingkar: telusuri lanjutan dari tujuan; bila kembali ke
  -- promo asal, batalkan.
  v_next := v_tujuan;
  WHILE v_next IS NOT NULL AND v_loop < 50 LOOP
    IF v_next = p_id_promo THEN
      RETURN QUERY SELECT 'SIKLUS'::text, p_id_promo, v_tujuan, v_sisa;
      RETURN;
    END IF;
    SELECT t.id_promo_lanjutan INTO v_next FROM t_promo t WHERE t.id_promo = v_next;
    v_loop := v_loop + 1;
  END LOOP;

  UPDATE t_promo
     SET budget_rupiah = budget_rupiah + v_sisa,
         updated_at = now()
   WHERE id_promo = v_tujuan;

  UPDATE t_promo
     SET budget_terpakai = budget_rupiah,
         aktif = false,
         updated_at = now()
   WHERE id_promo = p_id_promo;

  INSERT INTO t_promo_rollover (id_promo_asal, id_promo_tujuan, jumlah, tanggal_tutup)
  VALUES (p_id_promo, v_tujuan, v_sisa, p_tanggal);

  RETURN QUERY SELECT 'ROLLOVER'::text, p_id_promo, v_tujuan, v_sisa;
END;
$fn$;

COMMENT ON FUNCTION fn_promo_tutup_periode(integer, date) IS
  'Tutup periode promo: hangus atau pindahkan sisa budget ke id_promo_lanjutan.';

