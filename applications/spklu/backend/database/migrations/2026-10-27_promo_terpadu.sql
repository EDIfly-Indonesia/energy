  ADD COLUMN IF NOT EXISTS potongan_perkwh    double precision NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS potongan_rupiah    double precision NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS biaya_admin        double precision NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS biaya_layanan      double precision NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS kelas_layanan      varchar(20),
  ADD COLUMN IF NOT EXISTS pbjt_persen        double precision NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS dpp                double precision NOT NULL DEFAULT 0;

COMMENT ON COLUMN t_transaction.potongan_rupiah IS
  'Snapshot nilai promo saat transaksi dibuat; tidak berubah bila promo diubah.';

-- =============================================================================
-- 9. fn_promo_validasi — satu tempat untuk keempat cek (skenario 1/2/3)
--
--   5.1 kode promo masih berlaku      -> PROMO_NONAKTIF / BELUM_MULAI / KEDALUWARSA
--   5.2 budget promo masih tersedia   -> BUDGET_HABIS
--       Bila sisa budget lebih kecil dari nilai potongan, potongan DIPOTONG
--       SEBAGIAN sampai sisa budget dan transaksi tetap sah
--       (potongan_dibatasi = true). Keputusan bisnis #1.
--   5.3 ATPM sesuai merek kendaraan   -> KENDARAAN_TIDAK_COCOK
--       Wajib bersamaan dengan 5.4 (dua syarat). Keputusan bisnis #2.
--   5.4 akun terdaftar pada promo     -> BUKAN_PESERTA
--
-- Fungsi ini hanya MEMBACA. Pengurangan budget dilakukan fn_promo_pakai()
-- supaya validasi (quote) tidak mengubah data.
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_promo_validasi(
  p_id_user      integer,
  p_kode_promo   varchar,
  p_chargebox_id varchar,
  p_connector_id integer,
  p_kwh          double precision,
  p_tanggal      date DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  valid              boolean,
  alasan             text,
  id_promo           integer,
  kode_promo         varchar,
  nama_promo         varchar,
  id_mitra_promo     integer,
  tipe_potongan      varchar,
  nilai_potongan     double precision,
  harga_normal       double precision,
  potongan_rupiah    double precision,
  potongan_perkwh    double precision,
  potongan_dibatasi  boolean,
  sisa_budget        double precision,
  id_peserta         integer
)
LANGUAGE plpgsql STABLE AS $fn$
DECLARE
  v_kode        varchar(30);
  v_promo       t_promo%ROWTYPE;
  v_found       boolean := false;
  v_harga       double precision := 0;
  v_kwh         double precision;
  v_sisa        double precision := 0;
  v_potongan    double precision := 0;
  v_dibatasi    boolean := false;
  v_kwh_diskon  double precision;
  v_email       varchar(100);
  v_no_hp       varchar(30);
  v_id_peserta  integer;
  v_terpakai    integer;
  v_valid       boolean := false;
  v_alasan      text;
BEGIN
  v_kwh  := GREATEST(COALESCE(p_kwh, 0), 0);
  v_kode := upper(btrim(COALESCE(p_kode_promo, '')));

  IF v_kode = '' THEN
    v_alasan := 'KODE_KOSONG';
  ELSE
    -- Kualifikasi t.kode_promo: nama kolom ini juga nama kolom OUT (RETURNS
    -- TABLE), sehingga tanpa alias PostgreSQL menolak "column reference is
    -- ambiguous".
    SELECT t.* INTO v_promo FROM t_promo t WHERE t.kode_promo = v_kode;
    v_found := FOUND;
    IF NOT v_found THEN
      v_alasan := 'KODE_TIDAK_DITEMUKAN';
    END IF;
  END IF;

  -- Harga konektor dibaca lebih dulu supaya baris hasil penolakan pun bisa
  -- menampilkan harga normal.
  SELECT COALESCE(d.harga_perkwh, 0) INTO v_harga
    FROM t_connector_detail d
   WHERE d.chargebox_id = p_chargebox_id
     AND d.connector_id = p_connector_id;
  v_harga := COALESCE(v_harga, 0);

  IF v_found THEN
    v_sisa := v_promo.budget_rupiah - v_promo.budget_terpakai;

    IF NOT v_promo.aktif THEN
      v_alasan := 'PROMO_NONAKTIF';
    ELSIF p_tanggal < v_promo.tanggal_mulai THEN
      v_alasan := 'BELUM_MULAI';
    ELSIF p_tanggal > v_promo.tanggal_selesai THEN
      v_alasan := 'KEDALUWARSA';
    ELSE
      -- 5.4 Peserta: cocokkan id_user, atau email/no_hp akun mobile.
      IF v_promo.butuh_peserta THEN
        SELECT u.email, u.no_hp INTO v_email, v_no_hp
          FROM t_user_mobile u WHERE u.id_user = p_id_user;

        SELECT ps.id_peserta INTO v_id_peserta
          FROM t_promo_peserta ps
         WHERE ps.id_promo = v_promo.id_promo
           AND ps.status = 'active'
           AND (ps.tanggal_mulai   IS NULL OR p_tanggal >= ps.tanggal_mulai)
           AND (ps.tanggal_selesai IS NULL OR p_tanggal <= ps.tanggal_selesai)
           AND (
                ps.id_user = p_id_user
                OR (ps.id_user IS NULL AND ps.email IS NOT NULL
                    AND v_email IS NOT NULL AND lower(ps.email) = lower(v_email))
                OR (ps.id_user IS NULL AND ps.no_hp IS NOT NULL
                    AND v_no_hp IS NOT NULL AND ps.no_hp = v_no_hp)
               )
         ORDER BY (ps.id_user = p_id_user) DESC
         LIMIT 1;

        IF v_id_peserta IS NULL THEN
          v_alasan := 'BUKAN_PESERTA';
        END IF;
      END IF;

      -- 5.3 ATPM sesuai merek kendaraan (keputusan #2: WAJIB dua syarat,
      -- peserta DAN merek). Merek diwakili id_mitra_promo pada
      -- t_user_kendaraan; jenis mitra (atpm/hotel/asuransi) ada di
      -- t_promo_mitra sehingga tidak perlu kolom merek terpisah.
      IF v_alasan IS NULL AND v_promo.cek_kendaraan THEN
        IF NOT EXISTS (
          SELECT 1 FROM t_user_kendaraan k
           WHERE k.id_user = p_id_user
             AND k.id_mitra_promo = v_promo.id_mitra_promo
             AND k.aktif
        ) THEN
          v_alasan := 'KENDARAAN_TIDAK_COCOK';
        END IF;
      END IF;

      IF v_alasan IS NULL AND v_kwh < COALESCE(v_promo.min_kwh, 0) THEN
        v_alasan := 'MIN_KWH_TIDAK_TERPENUHI';
      END IF;

      -- 5.2 Budget.
      IF v_alasan IS NULL THEN
        IF v_sisa <= 0 THEN
          v_alasan := 'BUDGET_HABIS';
        END IF;
      END IF;

      -- Batas pemakaian per pengguna.
      IF v_alasan IS NULL AND v_promo.maks_pemakaian_per_user IS NOT NULL THEN
        SELECT count(*) INTO v_terpakai
          FROM t_promo_pemakaian p
         WHERE p.id_promo = v_promo.id_promo
           AND p.id_user = p_id_user
           AND p.status = 'aktif';
        IF v_terpakai >= v_promo.maks_pemakaian_per_user THEN
          v_alasan := 'BATAS_PEMAKAIAN';
        END IF;
      END IF;

      -- Hitung nilai potongan menurut tipe.
      IF v_alasan IS NULL THEN
        v_kwh_diskon := v_kwh;
        IF v_promo.maks_kwh IS NOT NULL THEN
          v_kwh_diskon := LEAST(v_kwh_diskon, v_promo.maks_kwh);
        END IF;

        v_potongan := CASE v_promo.tipe_potongan
          WHEN 'per_kwh' THEN v_promo.nilai_potongan * v_kwh_diskon
          WHEN 'persen'  THEN v_harga * v_kwh * v_promo.nilai_potongan / 100.0
          ELSE                v_promo.nilai_potongan
        END;

        IF v_promo.maks_potongan IS NOT NULL THEN
          v_potongan := LEAST(v_potongan, v_promo.maks_potongan);
        END IF;

        -- Potongan tidak boleh melebihi biaya energi itu sendiri.
        v_potongan := LEAST(GREATEST(v_potongan, 0), v_harga * v_kwh);

        -- KEPUTUSAN #1: budget tidak cukup -> potong sebagian sampai sisa
        -- budget, bukan ditolak. Transaksi tetap sah, pengguna tetap dapat
        -- promo walau nilainya lebih kecil dari yang dijanjikan.
        IF v_potongan > v_sisa THEN
          v_potongan := v_sisa;
          v_dibatasi := true;
        END IF;

        v_potongan := round(v_potongan::numeric, 2)::double precision;
        v_valid := v_potongan > 0;
        IF NOT v_valid THEN
          -- Sisa budget ada tapi terlalu kecil untuk dipotong (mis. 0,4 rupiah
          -- setelah pembulatan), atau biaya energi 0.
          v_alasan := CASE WHEN v_sisa <= 0 THEN 'BUDGET_HABIS'
                           ELSE 'NILAI_POTONGAN_NOL' END;
        END IF;
      END IF;
    END IF;
  END IF;

  RETURN QUERY SELECT
    v_valid,
    v_alasan,
    v_promo.id_promo,
    COALESCE(v_promo.kode_promo, v_kode),
    v_promo.nama,
    v_promo.id_mitra_promo,
    v_promo.tipe_potongan,
    COALESCE(v_promo.nilai_potongan, 0),
    v_harga,
    v_potongan,
    CASE WHEN v_kwh > 0
         THEN round((v_potongan / v_kwh)::numeric, 2)::double precision
         ELSE 0::double precision END,
    v_dibatasi,
    v_sisa,
    v_id_peserta;
END;
$fn$;

COMMENT ON FUNCTION fn_promo_validasi(integer, varchar, varchar, integer, double precision, date) IS
  'Validasi kode promo tanpa mengubah data. Dipakai getharga (quote) dan simpanorder.';

-- =============================================================================
-- 10. fn_promo_pakai — klaim budget + catat ledger secara atomik
--     Dipanggil saat order disimpan (setelah pembayaran/quote final), BUKAN
--     saat menampilkan harga.
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_promo_pakai(
  p_id_promo        integer,
  p_id_peserta      integer,
  p_id_user         integer,
  p_no_trans        varchar,
  p_kwh             double precision,
  p_harga_normal    double precision,
  p_potongan_rupiah double precision,
  p_potongan_perkwh double precision,
  p_harga_efektif   double precision
)
RETURNS boolean
LANGUAGE plpgsql AS $fn$
DECLARE
  v_ok boolean := false;
BEGIN
  -- Klaim budget secara atomik: satu UPDATE dengan syarat, sehingga dua
  -- transaksi bersamaan tidak bisa melampaui budget.
  UPDATE t_promo
     SET budget_terpakai = budget_terpakai + GREATEST(p_potongan_rupiah, 0),
         kuota_kwh_terpakai = kuota_kwh_terpakai + GREATEST(p_kwh, 0),
         updated_at = now()
   WHERE id_promo = p_id_promo
     AND budget_terpakai + GREATEST(p_potongan_rupiah, 0) <= budget_rupiah
     AND (kuota_kwh IS NULL
          OR kuota_kwh_terpakai + GREATEST(p_kwh, 0) <= kuota_kwh)
  RETURNING true INTO v_ok;

  IF NOT COALESCE(v_ok, false) THEN
    RETURN false;
  END IF;

  INSERT INTO t_promo_pemakaian (
    id_promo, id_peserta, id_user, no_trans, kwh, harga_normal,
    potongan_perkwh, harga_efektif, potongan_rupiah, status
  ) VALUES (
    p_id_promo, p_id_peserta, p_id_user, p_no_trans,
    GREATEST(p_kwh, 0), p_harga_normal,
    p_potongan_perkwh, p_harga_efektif, GREATEST(p_potongan_rupiah, 0), 'aktif'
  );

  RETURN true;
END;
$fn$;

CREATE OR REPLACE FUNCTION fn_promo_batal(
  p_no_trans varchar
)
RETURNS boolean
LANGUAGE plpgsql AS $fn$
DECLARE
  v_row t_promo_pemakaian%ROWTYPE;
BEGIN
  SELECT * INTO v_row FROM t_promo_pemakaian
   WHERE no_trans = p_no_trans AND status = 'aktif';
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE t_promo_pemakaian SET status = 'dibatalkan' WHERE id = v_row.id;

  UPDATE t_promo
     SET budget_terpakai = GREATEST(budget_terpakai - v_row.potongan_rupiah, 0),
         kuota_kwh_terpakai = GREATEST(kuota_kwh_terpakai - v_row.kwh, 0),
         updated_at = now()
   WHERE id_promo = v_row.id_promo;

  RETURN true;
END;
$fn$;

