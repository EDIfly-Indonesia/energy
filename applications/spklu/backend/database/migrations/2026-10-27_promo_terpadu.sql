CREATE OR REPLACE VIEW v_promo_ringkas AS
SELECT
  p.id_promo,
  p.kode_promo,
  p.nama,
  m.jenis_mitra,
  m.nama                                   AS nama_mitra,
  p.tipe_potongan,
  p.nilai_potongan,
  p.budget_rupiah,
  p.budget_terpakai,
  (p.budget_rupiah - p.budget_terpakai)    AS sisa_budget,
  CASE WHEN p.budget_rupiah > 0
       THEN round((p.budget_terpakai / p.budget_rupiah * 100)::numeric, 2)
       ELSE 0 END                          AS persen_terpakai,
  p.tanggal_mulai,
  p.tanggal_selesai,
  p.aktif,
  p.kebijakan_sisa,
  p.id_promo_lanjutan,
  (SELECT count(*) FROM t_promo_peserta ps
    WHERE ps.id_promo = p.id_promo AND ps.status = 'active')       AS jumlah_peserta,
  (SELECT count(*) FROM t_promo_pemakaian pk
    WHERE pk.id_promo = p.id_promo AND pk.status = 'aktif')        AS jumlah_transaksi,
  (SELECT COALESCE(sum(pk.potongan_rupiah), 0) FROM t_promo_pemakaian pk
    WHERE pk.id_promo = p.id_promo AND pk.status = 'aktif')        AS total_potongan
FROM t_promo p
JOIN t_promo_mitra m ON m.id_mitra_promo = p.id_mitra_promo;

-- Iklan yang layak tayang hari ini: aktif, dalam periode, promo masih punya
-- budget, dan belum mencapai batas tampil harian.
-- CATATAN: hitungan di sini GLOBAL (semua pengguna), untuk monitoring admin.
-- Batas tayang yang berlaku bagi pengguna dihitung per pengguna lewat
-- fn_promo_iklan_untuk_user() — keputusan #4.
CREATE OR REPLACE VIEW v_promo_iklan_tayang_hari_ini AS
SELECT
  i.id_iklan,
  i.id_promo,
  p.kode_promo,
  p.nama                    AS nama_promo,
  m.nama                    AS nama_mitra,
  i.foto,
  i.judul,
  i.target_url,
  i.urutan,
  i.maks_tayang_per_hari,
  COALESCE(t.jumlah, 0)     AS tayang_hari_ini,
  (i.maks_tayang_per_hari IS NULL
   OR COALESCE(t.jumlah, 0) < i.maks_tayang_per_hari) AS masih_bisa_tayang
FROM t_promo_iklan i
JOIN t_promo p        ON p.id_promo = i.id_promo
JOIN t_promo_mitra m  ON m.id_mitra_promo = p.id_mitra_promo
LEFT JOIN (
  SELECT id_iklan, count(*) AS jumlah
    FROM t_promo_iklan_tayang
   WHERE tanggal = CURRENT_DATE
   GROUP BY id_iklan
) t ON t.id_iklan = i.id_iklan
WHERE i.aktif
  AND p.aktif
  AND (i.tanggal_mulai   IS NULL OR CURRENT_DATE >= i.tanggal_mulai)
  AND (i.tanggal_selesai IS NULL OR CURRENT_DATE <= i.tanggal_selesai)
  AND CURRENT_DATE BETWEEN p.tanggal_mulai AND p.tanggal_selesai
  AND (p.budget_rupiah - p.budget_terpakai) > 0;

-- Eksposur EZ Charge: transaksi yang sudah dibayar dengan diskon promo tetapi
-- klaim budget gagal (budget habis antara order dan pembayaran). Selisih ini
-- ditanggung EZ Charge dan HARUS terlihat, bukan tersembunyi.
