--   t_user_kendaraan → dasar validasi "ATPM sesuai tipe kendaraan"
--   t_portal_user  → akun portal hotel/asuransi untuk mendaftarkan peserta
--   t_promo_pemakaian → ledger pemakaian + pengurangan budget
