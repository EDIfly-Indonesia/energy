JOIN t_promo p       ON p.id_promo = pk.id_promo
JOIN t_promo_mitra m ON m.id_mitra_promo = p.id_mitra_promo
WHERE pk.status = 'gagal_klaim';

-- =============================================================================
-- 13. Catatan: mengapa SATU kode promo per transaksi (keputusan #5)
--
-- Keputusan: satu transaksi hanya boleh memakai SATU kode promo.
--
-- Alasan teknis:
--   1. Setiap kode promo milik mitra berbeda. Bila dua promo dipakai bersama,
--      budget dua mitra harus dipotong pada satu transaksi. Porsi tiap mitra
--      menjadi tidak jelas, dan laporan barter per mitra kehilangan dasar.
--   2. Batas maks_potongan dan maks_kwh dirancang per promo. Menumpuk promo
--      membuat urutan penerapan menentukan hasil, sehingga angka bisa berbeda
--      untuk input yang sama (tidak deterministik).
--   3. Potongan tidak boleh melebihi biaya energi. Dengan dua promo, salah satu
--      promo bisa "termakan" promo lain dan nilainya tidak bisa direkonstruksi
--      dari t_transaction (satu kolom id_promo, satu potongan_rupiah).
--   4. t_promo_pemakaian.no_trans UNIQUE. Satu nomor transaksi = satu baris
--      pemakaian promo. Ini yang membuat pengurangan budget idempoten dan
--      aman terhadap pengiriman ulang (retry) dari klien.
--   5. Refund/pembatalan hanya perlu membalik satu klaim (fn_promo_batal),
--      bukan memilah beberapa klaim dari mitra berbeda.
--
-- Bila suatu saat penumpukan dibutuhkan, jalur yang benar BUKAN melonggarkan
-- UNIQUE(no_trans). Yang perlu diubah:
--   - tabel baru t_promo_pemakaian_detail (satu baris per promo per transaksi)
--   - t_transaction.potongan_rupiah menjadi jumlah seluruh detail
--   - urutan penerapan promo ditetapkan eksplisit (mis. prioritas menurun)
--   - validasi budget dilakukan per promo, bukan sekali
-- Sampai kebutuhan itu nyata, satu kode promo per transaksi dipertahankan.
--
-- Perilaku bila pengguna memasukkan kode kedua: kode yang sedang berlaku
-- diganti oleh kode baru (bukan digabung). Ini keputusan UI mobile, bukan
-- batasan database, dan perlu ditegaskan di layar pembelian.
-- =============================================================================

-- =============================================================================
-- 14. Penjaga urutan eksekusi
--
-- Bila 2026-10-23_fn_biaya_transaksi.sql (versi 4 argumen) dijalankan SETELAH
-- file ini, PostgreSQL menyimpan DUA overload dan pemanggilan 4 argumen
-- gagal dengan "function ... is not unique" — getharga dan simpanorder
-- langsung error. Blok ini menggagalkan migrasi secara eksplisit bila itu
-- terjadi, supaya masalahnya kelihatan saat migrasi, bukan saat produksi.
-- =============================================================================
DO $$
DECLARE
  v_jumlah integer;
BEGIN
  SELECT count(*) INTO v_jumlah
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public'
     AND p.proname = 'fn_biaya_transaksi';

  IF v_jumlah <> 1 THEN
    RAISE EXCEPTION
      'fn_biaya_transaksi punya % overload. Hapus versi 4-argumen lebih dulu: '
      'DROP FUNCTION fn_biaya_transaksi(varchar, integer, double precision, double precision);',
      v_jumlah;
  END IF;
END $$;

COMMIT;
