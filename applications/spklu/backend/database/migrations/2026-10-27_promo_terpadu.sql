CREATE OR REPLACE VIEW v_promo_eksposur AS
SELECT
  pk.id,
  pk.no_trans,
  pk.id_promo,
  p.kode_promo,
  p.nama                    AS nama_promo,
  m.nama                    AS nama_mitra,
  pk.id_user,
  pk.kwh,
  pk.harga_normal,
  pk.potongan_perkwh,
  pk.potongan_rupiah,
